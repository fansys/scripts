const fs = require("node:fs");
const path = require("node:path");
const ROOT = path.resolve(__dirname, "../..");
const SOURCE = "https://github.com/NobyDa/Script/blob/master/QuantumultX/Rewrite_lhie1.conf";
const SCRIPT = "https://cdn.jsdelivr.net/gh/fansys/scripts@main/Scripts/Rewrite_lhie1/request-header.js";

function literal(pattern) {
  let output = "";
  for (let i = 0; i < pattern.length; i++) {
    if (pattern[i] === "/") {
      let escapes = 0;
      for (let j = i - 1; j >= 0 && pattern[j] === "\\"; j--) escapes++;
      if (escapes % 2 === 0) output += "\\";
    }
    output += pattern[i];
  }
  return "/" + output + "/";
}

function parse(source) {
  let hostname;
  const rules = [];
  const headers = [];
  source.split(/\r?\n/).forEach((raw, index) => {
    const line = raw.trim();
    if (!line || line.startsWith("#")) return;
    if (line.startsWith("hostname = ")) { hostname = line.slice("hostname = ".length); return; }
    const match = /^(\S+) url (302|request-header|reject|reject-img|reject-dict)(?: (.*))?$/.exec(line);
    if (!match) throw new Error(`Unsupported source rule on line ${index + 1}: ${line}`);
    const [, pattern, action, value] = match;
    new RegExp(pattern);
    const rule = { line: index + 1, pattern, action, value, raw: line };
    rules.push(rule);
    if (action === "request-header") {
      const parts = value.split(" request-header ");
      if (parts.length !== 2) throw new Error(`Invalid header rule on line ${rule.line}`);
      if (parts[0] === String.raw`(\r\n)If-None-Match:.+(\r\n)` && parts[1] === "$1") {
        headers.push({ line: rule.line, pattern, remove: "If-None-Match" });
      } else {
        const replacement = /^\$1(.+)\$2([^\s]+)\$3$/.exec(parts[1]);
        if (parts[0] !== String.raw`^(.+?\s).+?(\s[\s\S]+?Host:).+?(\r\n)` || !replacement) {
          throw new Error(`Unsupported header rewrite on line ${rule.line}`);
        }
        headers.push({ line: rule.line, pattern, path: replacement[1], host: replacement[2] });
      }
    }
  });
  if (!hostname || !rules.length) throw new Error("Source must include hostname and rewrite rules");
  return { hostname, rules, headers };
}

function render(source, template) {
  const { hostname, rules, headers } = parse(source);
  const common = ["#!name=Rewrite_lhie1", "#!desc=lhie1 历史重写合集；上游更新日期 2021-08-26", "#!author=lhie1, NobyDa",
    "# 原始地址：" + SOURCE, "# SPDX-License-Identifier: GPL-3.0-only", "# Generated by Scripts/Rewrite_lhie1/build.cjs; edit the source and rebuild."];
  const qx = [...common, "hostname = " + hostname, ""];
  const loon = [...common, "#!loon_version=3.5.1(983)", "", "[Rewrite]"];
  const rocket = [...common, "#!system=ios", "", "[URL Rewrite]"];
  const loonScripts = [];
  const rocketScripts = [];
  for (const rule of rules) {
    if (rule.action === "request-header") {
      qx.push(`${rule.pattern} url script-request-header ${SCRIPT}`);
      loonScripts.push(`request if \${url} ~= ${literal(rule.pattern)} then script("${SCRIPT}") with tag="Rewrite_lhie1 ${rule.line}", timeout=10`);
      rocketScripts.push(`rewrite_lhie1_${rule.line} = type=http-request,pattern=${rule.pattern.replace(/,/g, "\\x2C")},script-path=${SCRIPT},timeout=10`);
    } else {
      qx.push(rule.raw);
      if (rule.action === "302") {
        loon.push(`request if \${url} ~= ${literal(rule.pattern)} then redirect(302, ${JSON.stringify(rule.value)})`);
        rocket.push(`${rule.pattern} ${rule.value} 302`);
      } else {
        const action = { reject: "reject", "reject-img": "reject_img(200)", "reject-dict": "reject_dict(200)" }[rule.action];
        loon.push(`request if \${url} ~= ${literal(rule.pattern)} then ${action}`);
        rocket.push(`${rule.pattern} - ${rule.action}`);
      }
    }
  }
  loon.push("", "[Script]", ...loonScripts, "", "[Mitm]", "hostname = " + hostname);
  rocket.push("", "[Script]", ...rocketScripts, "", "[MITM]", "hostname = %APPEND% " + hostname);
  return {
    "QuantumultX/Rewrite_lhie1.conf": qx.join("\n") + "\n",
    "Loon/Rewrite_lhie1.plugin": loon.join("\n") + "\n",
    "Shadowrocket/Rewrite_lhie1.sgmodule": rocket.join("\n") + "\n",
    "Scripts/Rewrite_lhie1/request-header.js": template.replace("__HEADER_RULES__", JSON.stringify(headers, null, 2))
  };
}

if (require.main === module) {
  const outputs = render(fs.readFileSync(path.join(__dirname, "upstream.conf"), "utf8"),
    fs.readFileSync(path.join(__dirname, "request-header.js.in"), "utf8"));
  for (const [name, content] of Object.entries(outputs)) fs.writeFileSync(path.join(ROOT, name), content);
  console.log("Generated 3 subscriptions and the shared request-header script.");
}
module.exports = { parse, literal, render };
